/**
 * Подсказки для выбранных категорий: специфичные наборы первыми,
 * затем универсальные, без дубликатов. Порядок совпадений сохраняется.
 */
export function presetLabelsForCategories(categories: string[] | null | undefined): string[] {
  const out: string[] = [];
  const push = (label: string) => {
    if (!out.includes(label)) out.push(label);
  };
  for (const category of categories ?? []) {
    for (const label of CHARACTERISTIC_PRESETS[category] ?? []) push(label);
  }
  for (const label of COMMON_CHARACTERISTIC_PRESETS) push(label);
  return out;
}
